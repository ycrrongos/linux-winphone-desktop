/// Exact desktop/Flatpak/Waydroid aliases; never guess from arbitrary substrings.
String? markUiApplicationAsset(String applicationId) {
  var id = applicationId
      .toLowerCase()
      .replaceFirst(RegExp(r'^(desktop|local):'), '')
      .split('/')
      .last;
  if (id.endsWith('.desktop')) id = id.substring(0, id.length - 8);
  if (id.startsWith('kcm_')) return 'settings';
  return _applications[id];
}

